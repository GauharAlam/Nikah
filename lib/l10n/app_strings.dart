/// Text for the current language. Stored values stay in English and are
/// translated only when shown.
String tr(String english) {
  if (AppStrings.current == AppLanguage.english) return english;
  final List<String>? row = AppStrings.table[english];
  if (row == null) return english;
  return row[AppStrings.current == AppLanguage.hindi ? 0 : 1];
}
